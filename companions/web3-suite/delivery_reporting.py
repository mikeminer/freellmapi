"""Authoritative delivery reports from runtime observations, not model prose."""
import hashlib
import json
from pathlib import Path
from datetime import datetime,timezone
from android_delivery import physical_ready
from work_ledger import load
from reliable_runtime import atomic_bytes


def source_changes(base,project):
    if not base or not Path(base).is_dir() or not project.is_dir():return None
    base=Path(base);names=set()
    for root in (base,project):
        for folder in ('src','public','android/app/src/main/java','android/app/src/main/res'):
            names.update(p.relative_to(root).as_posix() for p in (root/folder).rglob('*') if p.is_file() and not p.is_symlink())
    names.update(('package.json','package-lock.json','vite.config.mjs','index.html','android/app/build.gradle','android/build.gradle','android/settings.gradle','android/app/src/main/AndroidManifest.xml'))
    changed=[]
    for name in sorted(names):
        before=base/name;after=project/name
        before_hash=hashlib.sha256(before.read_bytes()).hexdigest() if before.is_file() else None
        after_hash=hashlib.sha256(after.read_bytes()).hexdigest() if after.is_file() else None
        if before_hash!=after_hash:changed.append({'path':name,'before_sha256':before_hash,'after_sha256':after_hash})
    return changed


def publish(agent,observed):
    if not physical_ready(observed):return None
    goal=observed['goal'];apk=observed['apk'];device=observed.get('device',{})
    if not agent.approve('Salvare REPORT.md/results.json dai controlli reali di APK e dispositivo, conservando eventuali bozze precedenti?'):return None
    receipts=load(agent.session).get('android_build_receipts',[])
    receipt=next((r for r in reversed(receipts) if r.get('apk',{}).get('sha256')==apk['sha256']),None)
    project=Path(receipt['project']) if receipt else next((p for p in Path(apk['path']).parents if (p/'package.json').is_file()),Path(agent.root))
    result={'schema_version':1,'status':'PASS','scope':'debug_apk_build_signature_bundle_install_launch',
            'verified_utc':datetime.now(timezone.utc).isoformat(),'package':apk['package'],'mint':goal.get('mint'),
            'run_id':goal.get('marker'),'apk':apk,'device':device,'build_receipt':receipt,
            'modified_source_files':source_changes(goal.get('base_project'),project),
            'checks':{'web_build':'PASS' if receipt and receipt.get('web_exit')==0 else 'NOT_VERIFIED',
                      'gradle_build':'PASS' if receipt and receipt.get('gradle_exit')==0 else 'NOT_VERIFIED',
                      'signature':'PASS' if apk.get('signature_verified') else 'NOT_VERIFIED',
                      'bundle':'PASS' if apk.get('bundled_html') else 'NOT_VERIFIED',
                      'installed_same_hash':'PASS' if device.get('same_apk_installed') else 'NOT_REQUESTED',
                      'running_pid':'PASS' if device.get('pid') else 'NOT_REQUESTED'},
            'limitations':['Gameplay touch, game-over/restart, orientation, performance and wallet transactions are not certified by build/install/PID checks.','Debug signing; no Store release.'],
            'provenance':'Generated by the runtime from APK inspection, native build receipt and ADB, without copying model assertions.'}
    try:
        logs=agent.seeker.logs(apk['package'],device.get('serial'),120)
        lines=[line for line in logs.splitlines() if 'PAGE_READY' in line]
        result['page_ready_evidence']=lines[-1] if lines else None
    except (RuntimeError,ValueError,OSError):result['page_ready_evidence']=None
    changed=result['modified_source_files']
    report=('# Consegna Android verificata\n\nPASS per il solo ambito build/firma/bundle/installazione/avvio.\n\n'
            f"- Package: `{apk['package']}`\n- Mint: `{goal.get('mint','')}`\n- Run: `{goal.get('marker','')}`\n"
            f"- APK: `{apk['path']}`\n- SHA256: `{apk['sha256']}`\n- Byte: {apk['bytes']}\n"
            f"- Certificato SHA256: `{apk.get('certificate_sha256','')}`\n- Seeker: `{device.get('serial','')}`; PID: `{device.get('pid','')}`\n\n"
            '## Controlli reali\n\n'+ '\n'.join('- '+key+': '+value for key,value in result['checks'].items())+
            '\n\n## Sorgenti modificati rispetto alla base\n\n'+('\n'.join('- '+r['path'] for r in changed) if changed else 'Nessuna modifica rilevata, oppure confronto non disponibile: vedere results.json.')+
            '\n\nIl marcatore debug richiesto è inserito nell’HTML generato dal builder; non implica una modifica del gameplay.\n\n## Limiti\n\n'+ '\n'.join('- '+line for line in result['limitations'])+
            '\n\nRapporto generato dal runtime da prove effettive; le eventuali bozze del modello sono conservate separatamente.\n')
    for name,raw in [('REPORT.md',report.encode('utf-8')),('results.json',json.dumps(result,ensure_ascii=False,indent=2).encode('utf-8'))]:
        path=Path(agent.root)/name
        if path.is_file() and path.read_bytes()!=raw:
            old=path.read_bytes();archive=path.with_name(name+'.model-draft-'+hashlib.sha256(old).hexdigest()[:10]+'.txt')
            if not archive.exists():atomic_bytes(archive,old)
        atomic_bytes(path,raw)
    return result


def render(result):
    return ('APK verificato e consegnato: '+result['package']+'\nToken: '+str(result.get('mint'))+
            '\nSHA256: '+result['apk']['sha256']+'\nSeeker: '+str(result['device'].get('serial'))+
            ' · PID: '+str(result['device'].get('pid'))+'\nProve salvate in REPORT.md e results.json.\n'
            'Build, firma, bundle, installazione e avvio verificati; gameplay completo e prestazioni non certificati.')
